"""
Meso Spectral Workflow Orchestrator
===================================

Module
------
Meso.meso_workflow

Purpose
-------
Coordinate the complete first-stage NeuroSeq Meso workflow from collected
Proto-state outputs through spectral family discovery and canonical result
generation.

Scientific Role
---------------
This module serves as the central orchestrator for Meso-level analysis. It
collects Proto-state firing-rate vectors and Louvain community assignments,
computes pairwise structural and activity-based relationships, constructs the
Meso similarity matrix, evaluates candidate family counts, and performs
spectral clustering.

The selected spectral labels are then converted into temporally ordered family
identifiers and used to generate canonical tables, affinity-network figures,
timelines, rasters, and diagnostic records. This module intentionally performs
workflow coordination only; the underlying scientific calculations remain
encapsulated within the dedicated Meso analysis modules.

Outputs
-------
This module writes pairwise similarity tables, S-score matrices, spectral
candidate diagnostics, canonical family labels, affinity graphs, materialized
family outputs, and a complete JSON diagnostic summary. It also returns a
dictionary containing the principal output paths and selected Meso parameters.

Author
------
Greg Owanga
Gregium Theory
"""

from __future__ import annotations
import argparse, json
from pathlib import Path
from types import SimpleNamespace
import numpy as np
import pandas as pd
from .meso_utils import ensure_dir
from .meso_proto_states import collect_proto_states
from .meso_pairs import compute_state_pairs
from .meso_proto_nmi import save_pairwise_nmi_from_pairs
from .meso_score import compute_s_scores, save_s_score_matrix
from .meso_spectral import evaluate_candidate_ks, joint_eigengap_modularity_score, spectral_labels
from .meso_labels import compress_labels_temporal_order, labels_to_family_df
from .meso_graphs import plot_affinity_graphs
from .meso_outputs import materialize_family_outputs


def run_meso_workflow(cfg=None, **kwargs):
    """
    Execute the complete spectral family-discovery workflow.

    Parameters
    ----------
    cfg : object or dict, optional
        Configuration object or dictionary containing the Meso workflow
        parameters. When omitted, configuration values are constructed from
        ``kwargs``.
    **kwargs
        Configuration values used when ``cfg`` is not provided.

    Returns
    -------
    dict
        Summary of the selected Meso solution together with the principal
        output files, diagnostic files, graph products, and materialized
        family-level results.

    Raises
    ------
    ValueError
        If ``BASE_DIR`` is not provided.
    RuntimeError
        If no valid pairwise state comparisons can be constructed.

    Notes
    -----
    The number of spectral families may be supplied manually through
    ``SPECTRAL_N_CLUSTERS``. Otherwise, candidate values of ``k`` are evaluated
    using the joint normalized eigengap and weighted modularity criterion.

    Temporal cleanup and subtype discovery are disabled in this workflow.
    Therefore, the final family assignments are determined exclusively by the
    spectral clustering solution.
    """

    # Normalize dictionary and keyword configurations to attribute access.
    if cfg is None: cfg = SimpleNamespace(**kwargs)
    elif isinstance(cfg, dict): cfg = SimpleNamespace(**cfg)

    # Resolve the canonical Sequence and Meso output directories.
    base_dir = str(getattr(cfg,"BASE_DIR","")).strip()
    if not base_dir: raise ValueError("cfg.BASE_DIR required")
    sequence_sub = str(getattr(cfg,"SEQUENCE_SUBFOLDER","Sequence")).strip()
    root = ensure_dir(Path(base_dir)/sequence_sub)
    out = ensure_dir(root/"Meso_Sequence")

    # Collect firing-rate vectors and Louvain partitions generated by Micro.
    state_vectors, state_clusters = collect_proto_states(base_dir)
    state_ids = list(state_vectors)

    # Return a diagnostic result when no Proto-states are available.
    if not state_ids: return {"threshold_mode":"no_states","reason":"No micro-states detected.","n_states":0,"root_sequence_folder":str(root)}

    # Materialize the deterministic single-family fallback for one state.
    if len(state_ids)==1:
        fallback=ensure_dir(out/"One_State_Fallback")
        df=pd.DataFrame([{"proto_state_index":0,"Unique_ID":state_ids[0],"Spectral_Label_Raw":0,"Spectral_Label":0,"Component_Label":"A","Cluster_Label":"A"}])
        csv=fallback/"spectral_state_labels.csv"; df.to_csv(csv,index=False)
        materialized=materialize_family_outputs(
            out_dir=str(fallback/"Primary_Output"),state_vectors=state_vectors,
            state_ids=state_ids,family_label_csv=str(csv),
            data_folder=str(getattr(cfg,"DATA_FOLDER","")),
            do_plots=bool(getattr(cfg,"DO_GRAPH",True)))
        return {"threshold_mode":"one_state_fallback","n_components":1,
                "selection_folder":str(fallback),"family_label_csv":str(csv),
                "materialized_outputs":materialized}

    # Compute pairwise community similarity and firing-rate distance.
    state_ids, pairs = compute_state_pairs(state_vectors,state_clusters)
    if pairs.empty: raise RuntimeError("Pairs empty")
    pairs_csv=out/"pairs_nmi_dist.csv"; pairs.to_csv(pairs_csv,index=False)
    # Reuse the same NMI measurements for the Proto-state NMI outputs.
    save_pairwise_nmi_from_pairs(pairs, state_ids, state_clusters, root/"Proto-States")

    # Convert pairwise measurements into the canonical Meso similarity score.
    scored, score_diag = compute_s_scores(pairs,n_states=len(state_ids))
    scored_csv=out/"pairs_nmi_dist_score.csv"; scored.to_csv(scored_csv,index=False)

    # Save the dense S-score matrix used as the spectral affinity matrix.
    s_csv=save_s_score_matrix(pairs_score=scored,state_ids=state_ids,out_csv=out/"s_score_matrix.csv")
    affinity_csv=out/"spectral_similarity_matrix.csv"; affinity_csv.write_text(Path(s_csv).read_text(),encoding="utf-8")
    A=pd.read_csv(s_csv,index_col=0).to_numpy(float)

    # Read the spectral-clustering and candidate-selection configuration.
    manual=getattr(cfg,"SPECTRAL_N_CLUSTERS",None)
    min_k=int(getattr(cfg,"SPECTRAL_MIN_K",2)); max_k=getattr(cfg,"SPECTRAL_MAX_K",None)
    if max_k is not None:
        try: max_k=int(max_k)
        except Exception: max_k=None
    seed=int(getattr(cfg,"SPECTRAL_RANDOM_STATE",getattr(cfg,"MESO_SEED",42)))
    solver=str(getattr(cfg,"SPECTRAL_EIGEN_SOLVER","arpack"))
    top_n=int(getattr(cfg,"SPECTRAL_TOP_N_EIGENGAP_CANDIDATES",8))

    # Use the requested family count when a manual override is supplied.
    if manual is not None:
        selected_k=int(manual)
        candidates=pd.DataFrame([{"candidate_k":selected_k,"eigengap_norm":1.0,"modularity_norm":1.0,"joint_eigengap_modularity_score":2.0,"selected_by_joint_eigengap_modularity":True}])
        k_diag={"reason":"manual_SPECTRAL_N_CLUSTERS_override","selected_k":selected_k,"joint_score_formula":"normalized_eigengap + normalized_weighted_modularity","joint_score":2.0,"candidate_ks_tested":[selected_k]}

    # Otherwise evaluate strong eigengap candidates using graph modularity.
    else:
        _, eig_diag, candidates=evaluate_candidate_ks(A,min_k=min_k,max_k=max_k,top_n=top_n,random_state=seed,eigen_solver=solver)
        candidates["joint_eigengap_modularity_score"]=joint_eigengap_modularity_score(candidates["eigengap_norm"].to_numpy(float),candidates["modularity_norm"].to_numpy(float))
        idx=candidates["joint_eigengap_modularity_score"].astype(float).idxmax(); selected_k=int(candidates.loc[idx,"candidate_k"])
        candidates["selected_by_joint_eigengap_modularity"]=candidates["candidate_k"].astype(int)==selected_k
        k_diag={"reason":"joint_eigengap_modularity_k_selection","selected_k":selected_k,"joint_score_formula":"normalized_eigengap + normalized_weighted_modularity","joint_score":float(candidates.loc[idx,"joint_eigengap_modularity_score"]),"candidate_ks_tested":[int(x) for x in candidates["candidate_k"]],"eigengap_diagnostics":eig_diag}

    # Preserve the complete candidate-ranking table for reproducibility.
    candidate_csv=out/"spectral_candidate_k_scores.csv"; candidates.to_csv(candidate_csv,index=False)

    # Compute spectral family assignments at the selected number of families.
    raw=spectral_labels(A,n_clusters=selected_k,random_state=seed,eigen_solver=solver)

    # Reorder integer labels according to first temporal appearance.
    labels=compress_labels_temporal_order(raw.copy())

    # Build and save the canonical Proto-state-to-family mapping.
    family=labels_to_family_df(state_ids,labels,raw)
    family_csv=out/"spectral_state_labels.csv"; family.to_csv(family_csv,index=False)

    # Generate affinity-network visualizations of the spectral solution.
    graph=plot_affinity_graphs(A=A,state_ids=state_ids,labels=labels,out_dir=out/"Similarity_Graphs",seed=int(getattr(cfg,"MESO_SEED",42)),edge_quantile=float(getattr(cfg,"AFFINITY_GRAPH_EDGE_QUANTILE",0.90)),max_edges=int(getattr(cfg,"AFFINITY_GRAPH_MAX_EDGES",5000)))

    # Generate canonical family timelines, rasters, and output tables.
    materialized=materialize_family_outputs(out_dir=str(out/"Primary_Output"),state_vectors=state_vectors,state_ids=state_ids,family_label_csv=str(family_csv),data_folder=str(getattr(cfg,"DATA_FOLDER","")),do_plots=bool(getattr(cfg,"DO_GRAPH",True)))

    # Assemble complete diagnostic metadata for the selected Meso solution.
    diagnostics={"selection_mode":"joint_eigengap_modularity","threshold_mode":"spectral_joint_eigengap_modularity_no_cleanup_no_subtypes","score_mode":"original_exponential_S_score_affinity_matrix","selected_k":selected_k,"n_spectral_labels":int(len(set(labels.tolist()))),"k_selection":k_diag,"spectral_eigen_solver":solver,"temporal_cleanup":{"cleanup_mode":"disabled","reason":"family_labels_are_assigned_only_by_spectral_clustering","n_changed_nodes":0},"subtype_discovery":"disabled","score_diagnostics":score_diag,"n_micro_states":len(state_ids),"n_family_labels":int(family["Component_Label"].nunique()),"pairs_score_csv":str(scored_csv),"s_score_matrix_csv":str(s_csv),"affinity_matrix_csv":str(affinity_csv),"candidate_scores_csv":str(candidate_csv),"family_label_csv":str(family_csv),"affinity_graph_outputs":graph,"materialized_outputs":materialized}
    diag_json=out/"meso_spectral_diagnostics.json"; diag_json.write_text(json.dumps(diagnostics,indent=2),encoding="utf-8")

    # Report the principal Meso selection results to the console.
    print("\nMESO: joint eigengap + modularity"); print(f"joint selected k       = {selected_k}"); print(f"joint-selection folder = {out}")

    # Return the canonical workflow summary to the calling orchestrator.
    return {"threshold_mode":"spectral_joint_eigengap_modularity_only","selected_k":selected_k,"joint_eigengap_modularity_k":selected_k,"root_sequence_folder":str(root),"quantify_folder":str(out),"pairs_nmi_dist_csv":str(pairs_csv),"candidate_scores_csv":str(candidate_csv),"s_score_matrix_csv":str(s_csv),"affinity_matrix_csv":str(affinity_csv),"family_label_csv":str(family_csv),"diagnostics_json":str(diag_json),"affinity_graph_outputs":graph,"materialized_outputs":materialized}


def _main_cli():
    """
    Execute the Meso workflow from a JSON command-line payload.

    Notes
    -----
    The command-line interface accepts a serialized configuration dictionary
    through ``--payload-json`` and prints the returned workflow summary as
    JSON for integration with external orchestration scripts.
    """

    # Parse the serialized configuration and execute the workflow.
    parser=argparse.ArgumentParser(); parser.add_argument("--payload-json",type=str,required=True); args=parser.parse_args(); print(json.dumps(run_meso_workflow(json.loads(args.payload_json))))


# Provide direct command-line execution while preserving import behavior.
if __name__=="__main__": _main_cli()