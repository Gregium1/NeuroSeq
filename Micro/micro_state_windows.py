"""
Consensus State Window Construction and State-Level Louvain Clustering
======================================================================

Module
------
Micro.micro_state_windows

Purpose
-------
Construct the final consensus Micro state windows and perform Louvain
community detection independently within each state.

Following the automatic gamma sweep, NeuroSeq identifies consensus temporal
boundaries from critical points detected across all gamma values. These
boundaries partition the recording into the final sequence of temporal states.

Within every resulting state interval, a neuronal similarity graph is
constructed and Louvain community detection is performed using the selected
representative Louvain resolution.

Scientific Role
---------------
This module separates two fundamentally different operations:

1. Temporal segmentation
   Final state boundaries are determined exclusively from the consensus
   adjacent-window NMI representation.

2. Within-state neuronal organization
   For each consensus state, neuronal firing activity is converted into a
   weighted similarity graph and Louvain community detection identifies the
   underlying neuronal communities.

Suppose a consensus state spans

    [t_start, t_end].

For every neuron, the total number of spikes within this interval is counted.

The similarity between neurons i and j is defined from the difference in their
spike counts,

    Δ = |c_i − c_j|,

through the linear similarity

    w = max(0, 100 − Δ / duration),

where

    duration = t_end − t_start.

The resulting weighted graph is clustered once using the representative
Louvain resolution.

Outputs
-------
The canonical outputs written under

    State_Windows/

are

``louvain_clusters_all_states.csv``
    Complete Louvain assignments together with temporal state information.

``state__x_cluster.csv``
    Compact table containing only

    - State
    - Neuron_ID
    - Cluster

used by downstream pairwise state analyses.

Author
------
Greg Owanga
Gregium Theory
"""

from __future__ import annotations

import glob
import os

import community as community_louvain
import networkx as nx
import numpy as np
import pandas as pd

from .micro_utils import (
    _ensure_dir,
    _find_latest_counts_csv,
    _load_spike_times,
    _parse_counts_bounds,
)


def run_state_windows_louvain(
    base_dir: str,
    data_dir: str,
    nmi_threshold: float,
    lambda_val: float,
    window_size: float,
    louvain_resolution: float,
    seed: int,
    use_auto_find_counts_csv: bool,
    counts_csv_search_root: str,
    manual_start_time: float,
    manual_end_time: float,
):
    """
    Construct the final consensus state windows and perform Louvain
    community detection independently within each state.

    Parameters
    ----------
    base_dir : str
        Directory containing the canonical Micro outputs.
    data_dir : str
        Directory containing the SU_*.csv spike files.
    nmi_threshold : float
        Threshold used to identify consensus state boundaries.
    lambda_val : float
        Lambda value used when generating the adjacent-window NMI table.
    window_size : float
        Original sliding-window duration.
    louvain_resolution : float
        Representative Louvain resolution used inside each consensus state.
    seed : int
        Random seed supplied to Louvain.
    use_auto_find_counts_csv : bool
        Automatically recover recording bounds from the latest counts table.
    counts_csv_search_root : str
        Search directory for counts tables.
    manual_start_time : float
        User-specified recording start time.
    manual_end_time : float
        User-specified recording end time.

    Returns
    -------
    dict
        Canonical output paths generated by this module.

    Raises
    ------
    FileNotFoundError
        If required inputs cannot be located.
    ValueError
        If the NMI table is malformed.
    RuntimeError
        If no valid state assignments are produced.

    Notes
    -----
    Consensus temporal boundaries originate from the all-gamma critical-point
    analysis. The representative Louvain resolution is used only to identify
    neuronal communities within each already-defined state.
    """

    # Verify that the canonical Micro output directory exists.
    if not os.path.isdir(base_dir):
        raise FileNotFoundError(f"Base directory not found: {base_dir}")

    # Locate the consensus adjacent-window NMI representation produced by the
    # automatic gamma sweep.
    nmi_csv = os.path.join(base_dir, f"nmi_adjacent_windows_lambda_{lambda_val}.csv")
    if not os.path.exists(nmi_csv):
        matches = glob.glob(
            os.path.join(base_dir, "**", f"nmi_adjacent_windows_lambda_{lambda_val}.csv"),
            recursive=True,
        )
        if not matches:
            raise FileNotFoundError("NMI CSV not found.")
        matches.sort(key=lambda p: os.path.getmtime(p), reverse=True)
        nmi_csv = matches[0]

    # Load and validate the consensus NMI representation.
    nmi_df = pd.read_csv(nmi_csv)
    if not {"Start_Time_s", "NMI"}.issubset(nmi_df.columns):
        raise ValueError("NMI CSV missing ['Start_Time_s', 'NMI'].")

    # Initialize the recording interval.
    start_time = float(manual_start_time)
    end_time = float(manual_end_time)

    # Optionally recover the recording interval automatically.
    if use_auto_find_counts_csv:
        try:
            counts_csv = _find_latest_counts_csv(counts_csv_search_root, window_size)
            s, e, _ = _parse_counts_bounds(counts_csv)
            if s is not None and e is not None:
                start_time, end_time = float(s), float(e)
        except Exception:
            pass

    # Locate all recorded neurons.
    su_files = sorted(
        f for f in os.listdir(data_dir)
        if f.startswith("SU_") and f.endswith(".csv")
    )
    su_ids = [os.path.splitext(f)[0] for f in su_files]
    if not su_ids:
        raise FileNotFoundError(f"No SU_*.csv files found in {data_dir}")

    # Load spike trains for every neuron.
    spikes = {}
    for su in su_ids:
        try:
            spikes[su] = _load_spike_times(os.path.join(data_dir, su + ".csv"))
        except Exception:
            spikes[su] = np.array([], dtype=float)

    # Recover consensus temporal boundaries.
    times = nmi_df["Start_Time_s"].to_numpy(float)
    nmis = nmi_df["NMI"].to_numpy(float)
    if times.size == 0:
        raise ValueError("NMI CSV contains no adjacent-window comparisons.")

    eps = 1e-9
    if np.nanmin(times) < start_time - eps or np.nanmax(times) <= start_time + window_size + eps:
        times = times + start_time

    dividers = sorted({
        float(t) for t, n in zip(times, nmis)
        if n < nmi_threshold and start_time < t < end_time
    })
    edges = [start_time] + dividers + [end_time]

    # Create the canonical output directory.
    out_dir = os.path.join(base_dir, "State_Windows")
    _ensure_dir(out_dir)

    # Stable neuron/node mappings.
    neuron_to_id = {su: i + 1 for i, su in enumerate(su_ids)}
    id_to_neuron = {i + 1: su for i, su in enumerate(su_ids)}
    cluster_out = []

    # Cluster each consensus state independently.
    for idx, (s0, s1) in enumerate(zip(edges[:-1], edges[1:]), start=1):
        duration = float(s1 - s0)
        if duration <= 0:
            continue

        counts = {
            su: int(np.sum((spikes[su] >= s0) & (spikes[su] <= s1)))
            if spikes[su].size else 0
            for su in su_ids
        }

        # Construct the weighted neuronal similarity graph.
        graph = nx.Graph()
        graph.add_nodes_from(neuron_to_id.values())

        for i, su_i in enumerate(su_ids):
            for su_j in su_ids[i + 1:]:
                delta = abs(counts[su_i] - counts[su_j])
                weight = max(0.0, 100.0 - delta / duration)
                graph.add_edge(
                    neuron_to_id[su_i],
                    neuron_to_id[su_j],
                    weight=float(weight),
                )

        # Empty graphs receive a single community.
        if graph.number_of_edges() == 0:
            partition = {node: 0 for node in graph.nodes()}
        else:
            partition = community_louvain.best_partition(
                graph,
                weight="weight",
                resolution=float(louvain_resolution),
                random_state=int(seed),
            )

        state = f"State_{idx}"

        # Store the complete Louvain partition.
        state_df = pd.DataFrame({
            "Node_ID": list(partition.keys()),
            "Neuron_ID": [id_to_neuron[int(node)] for node in partition],
            "Cluster": [int(value) for value in partition.values()],
            "State": state,
            "Start": float(s0),
            "End": float(s1),
        }).sort_values("Node_ID")

        cluster_out.append(state_df)

    if not cluster_out:
        raise RuntimeError("No valid state Louvain assignments were produced.")

    # Save canonical outputs.
    all_df = pd.concat(cluster_out, ignore_index=True)
    all_df.to_csv(os.path.join(out_dir, "louvain_clusters_all_states.csv"), index=False)

    all_df[["State", "Neuron_ID", "Cluster"]].to_csv(
        os.path.join(out_dir, "state__x_cluster.csv"),
        index=False,
    )

    # Return canonical output locations.
    return {
        "state_windows_dir": out_dir,
        "louvain_clusters_all_states_csv": os.path.join(out_dir, "louvain_clusters_all_states.csv"),
        "state_x_cluster_csv": os.path.join(out_dir, "state__x_cluster.csv"),
    }